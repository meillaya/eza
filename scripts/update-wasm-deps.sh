#!/usr/bin/env bash
# Refresh the pinned WebAssembly dependency set.
#
# Run from a development shell (needs wasm32-wasi-cabal, python3 and curl):
#
#   bash scripts/update-wasm-deps.sh
#
# Use this after changing cabal.project.wasm or a wasm package dependency. It
# refreshes the three files that must change together:
#
#   cabal.project.wasm.freeze   exact solver versions
#   nix/wasm-hackage.nix        one fixed-output tarball URL + SRI hash each
#   nix/wasm-cabal/             the latest Hackage revision of each .cabal file
#
# The Nix build then rebuilds the bundle offline from those pins. Review the
# diff: a version bump should be a deliberate change, not incidental churn.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if ! command -v wasm32-wasi-cabal >/dev/null 2>&1; then
  echo "update-wasm-deps: wasm32-wasi-cabal not found; enter the dev environment with 'devenv shell'" >&2
  exit 1
fi
if ! command -v python3 >/dev/null 2>&1; then
  echo "update-wasm-deps: python3 not found; enter the dev environment with 'devenv shell'" >&2
  exit 1
fi

# The same CABAL_DIR scripts/build-web.sh uses, so the plan matches the
# development build and the pinned index-state.
export CABAL_DIR="${EZA_WASM_CABAL_DIR:-$ROOT/.devenv/cabal-wasm}"

echo "update-wasm-deps: resolving the wasm build plan" >&2
# A dedicated builddir: dist-newstyle/cache/plan.json belongs to whichever
# native/wasm build ran last, and the native project is a different plan.
PLAN_BUILD_DIR="$ROOT/.dsh-wasm-plan"
rm -rf "$PLAN_BUILD_DIR"
wasm32-wasi-cabal build --project-file=cabal.project.wasm --builddir="$PLAN_BUILD_DIR" --dry-run eza-web >/dev/null

plan="$PLAN_BUILD_DIR/cache/plan.json"
if [ ! -f "$plan" ]; then
  echo "update-wasm-deps: $plan was not written; run 'wasm32-wasi-cabal build --project-file=cabal.project.wasm eza-web --dry-run' first" >&2
  exit 1
fi

echo "update-wasm-deps: freezing wasm dependency versions" >&2
wasm32-wasi-cabal freeze --project-file=cabal.project.wasm --builddir="$PLAN_BUILD_DIR" >/dev/null

echo "update-wasm-deps: refreshing nix/wasm-hackage.nix and nix/wasm-cabal/" >&2
mkdir -p nix/wasm-cabal
python3 - "$ROOT" <<'PY'
import base64
import hashlib
import json
import os
import subprocess
import sys
import tempfile

root = sys.argv[1]
with open(os.path.join(root, ".dsh-wasm-plan/cache/plan.json"), encoding="utf-8") as plan_file:
    plan = json.load(plan_file)

packages = {}
for unit in plan["install-plan"]:
    if unit.get("style") == "local" or unit.get("type") != "configured":
        continue
    packages[unit["pkg-name"]] = unit["pkg-version"]

cabal_dir = os.path.join(root, "nix/wasm-cabal")
header = """# Hackage release tarballs the WebAssembly client's dependency plan needs.
# Generated by scripts/update-wasm-deps.sh from
# .dsh-wasm-plan/cache/plan.json for cabal.project.wasm; the versions are pinned
# by cabal.project.wasm.freeze and the .cabal metadata by nix/wasm-cabal/, so
# this list changes only when the wasm dependency set changes.
#
# Each entry is a fixed-output fetchurl: the wasm derivation never touches the
# network, and packages.<system>.eza-web builds a local Hackage repository from
# these tarballs and nix/wasm-cabal/.
{
  packages = ["""

entries = []
with tempfile.TemporaryDirectory() as temp_dir:
    for name, version in sorted(packages.items()):
        tarball = os.path.join(temp_dir, f"{name}-{version}.tar.gz")
        url = f"https://hackage.haskell.org/package/{name}-{version}/{name}-{version}.tar.gz"
        subprocess.run(["curl", "-fsSL", "--http1.1", "--retry", "5", "--retry-all-errors", "-o", tarball, url], check=True)
        with open(tarball, "rb") as tarball_file:
            digest = hashlib.sha256(tarball_file.read()).digest()
        sri = "sha256-" + base64.b64encode(digest).decode()
        entries.append(f'    {{ name = "{name}"; version = "{version}"; hash = "{sri}"; }}')
        cabal_path = os.path.join(cabal_dir, f"{name}-{version}.cabal")
        cabal_url = f"https://hackage.haskell.org/package/{name}-{version}/{name}.cabal"
        subprocess.run(["curl", "-fsSL", "--http1.1", "--retry", "5", "--retry-all-errors", "-o", cabal_path, cabal_url], check=True)
        # Normalise to LF so the vendored metadata is stable across checkouts.
        with open(cabal_path, "rb") as cabal_file:
            data = cabal_file.read().replace(b"\r\n", b"\n")
        with open(cabal_path, "wb") as cabal_file:
            cabal_file.write(data)

lines = [header, *entries, "  ];", "}", ""]
with open(os.path.join(root, "nix/wasm-hackage.nix"), "w", encoding="utf-8") as package_file:
    package_file.write("\n".join(lines))
print(f"update-wasm-deps: wrote {len(entries)} packages", file=sys.stderr)
PY

rm -rf "$PLAN_BUILD_DIR"
echo "update-wasm-deps: done; review the diff and build with 'nix build .#eza-web'" >&2
