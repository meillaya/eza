{- | The MVU update function: a thin dispatcher over the per-route-group update
modules, plus the browser subscriptions.

Every group module exposes a total @handle@; the dispatcher below routes each
'Action' constructor to the one group that owns it, so the compiler enforces
that a new action gets a home. Behaviour lives in the group modules; the ledger
reducer itself lives in the native @eza-web-logic@ package.
-}
