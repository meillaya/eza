{-# LANGUAGE OverloadedStrings #-}

{- | The served app shell and the hashed asset URLs the server-rendered auth
pages load.

The shell is generated by @scripts/bundle-web.sh@ from the tracked template
@static\/template\/index.html@; the server serves those generated bytes with
@Cache-Control: no-store@. The auth pages are rendered per request in
'Eza.Pages', and this module hands them the hashed URLs from the asset
manifest, so no page keeps its own asset list.
-}
module Eza.Shell (
    PageAssets (..),
    pageAssets,
    shellBuildId,
    shellPage,
) where

import qualified Data.ByteString.Lazy as LBS
import qualified Data.Map.Strict as Map
import Data.Maybe (fromMaybe)
import Data.Text (Text)
import qualified Data.Text as T
import qualified Data.Text.Encoding as TE
import Network.HTTP.Types (hCacheControl, hContentType, status200)
import Network.Wai (Response, responseLBS)

import Eza.Assets (Assets, assetPath, assetsBuildId, assetsIndexHtml, assetsShellPaths)

{- | The hashed URLs the server-rendered auth and recovery pages load. Every
field falls back to the unhashed path when the server runs without a bundle,
which keeps the placeholder/auth pages working in tests and in @--no-static@
mode.
-}
data PageAssets = PageAssets
    { paCss :: Text
    , paThemeJs :: Text
    , paAuthJs :: Text
    , paFavicon :: Text
    }

pageAssets :: Assets -> PageAssets
pageAssets assets =
    PageAssets
        { paCss = shellAsset assets "css" "eza.css"
        , paThemeJs = shellAsset assets "theme_js" "theme.js"
        , paAuthJs = shellAsset assets "auth_js" "auth.js"
        , paFavicon = shellAsset assets "favicon" "favicon.svg"
        }

shellAsset :: Assets -> Text -> Text -> Text
shellAsset assets shellKey logicalName =
    fromMaybe (assetPath assets logicalName) (Map.lookup shellKey (assetsShellPaths assets))

shellBuildId :: Assets -> Text
shellBuildId = assetsBuildId

{- | The generated app shell. It is never stored: a rebuild must reach the next
navigation. The gzip middleware compresses the body above its size threshold,
so the shell does not need a precompressed sidecar.
-}
shellPage :: Assets -> Response
shellPage assets =
    responseLBS
        status200
        ( [(hContentType, "text/html; charset=utf-8"), (hCacheControl, "no-store")]
            <> [("X-Eza-Build", TE.encodeUtf8 buildId) | not (T.null buildId)]
        )
        (LBS.fromStrict (assetsIndexHtml assets))
  where
    buildId = assetsBuildId assets
